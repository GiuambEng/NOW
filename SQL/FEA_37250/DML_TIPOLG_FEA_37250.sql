SET SERVEROUTPUT ON;
BEGIN
    DBMS_OUTPUT.PUT_LINE ('UPDATE APPUSER.ANAGRAFICA_ESITO_OPEN_FIBER');
    UPDATE APPUSER.ANAGRAFICA_ESITO_OPEN_FIBER 
	   SET CODCLUSTER='AUTO'
	 WHERE CATEGORIA='ACQUISITOKO' 
	   AND CODICEMOTIVAZIONE IN ('B00','B01','B02','B09')
	   AND CODCLUSTER='OA'
	   AND METODO='OF_StatusUpdate';
    DBMS_OUTPUT.PUT_LINE ('UPDATE APPUSER.TIPOLOGIA_ESITO_OPENFIBER');
    UPDATE APPUSER.TIPOLOGIA_ESITO_OPENFIBER 
	   SET IDTPLG_EVENTO=185
	 WHERE CODICE_MOTIVAZIONE IN ('B00','B01','B02','B09')
	   AND EVENTO_OPENFIBER='OF_StatusUpdate'
	   AND ID_TIPLG_ESITO_OPENFIBER IN (5,6,7,11)
	   AND IDTPLG_EVENTO=184;   
    COMMIT;   
    DBMS_OUTPUT.PUT_LINE ('Commit executed');
EXCEPTION 
  WHEN OTHERS THEN
    dbms_output.put_line('ERRORE - '||SQLERRM);
    ROLLBACK;
    dbms_output.put_line('Rollback executed');
END;
